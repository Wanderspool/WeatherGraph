"""
weathergraph.cf_meta
=====================

CF-1.11 (Climate and Forecast) convention metadata for the WeatherGraph
inference engine.

This module defines standard names, units, and long names for every
atmospheric variable and coordinate produced by the engine, following
the UDUNITS-compatible naming required by MetPy, xCDAT, and the broader
climate-science Python ecosystem.

References
----------
- CF Conventions 1.11: https://cfconventions.org/Data/cf-conventions/cf-conventions-1.11/cf-conventions.html
- UDUNITS: https://www.unidata.ucar.edu/software/udunits/
"""

from __future__ import annotations

from typing import Any, Dict, List, Optional, Tuple

import numpy as np
import pandas as pd
import xarray as xr


